"""Initial administrator and clearly synthetic demo organizations/users.

- `create_admin`: first SYSTEM_ADMIN + organization (password supplied by the operator).
- `seed_demo`: two demo organizations that split the synthetic population by region, one user per
  role in each, staff assignments and one verified patient link per organization (through the
  normal invitation + date-of-birth workflow). E-mail addresses use the reserved `.invalid` TLD.
  Idempotent: existing organizations/users are reused and existing passwords are never changed.

No password is hard-coded: the caller passes one (`DEMO_IDENTITY_PASSWORD`) or each account gets
a random password that is printed once by the CLI.
"""

from __future__ import annotations

import logging
import secrets
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from dataclasses import dataclass

from sqlalchemy import select

from app.core.config import settings
from app.core.permissions import Role
from app.models.identity import Organization
from app.repositories.read_repo import MemoryReadRepository, PostgresReadRepository, ReadRepository
from app.services.identity import directory
from app.services.identity import service as auth
from app.services.identity.store import identity_session

logger = logging.getLogger("pulsereach.identity.demo")

DEMO_DOMAIN = "demo.pulsereach.invalid"
DEMO_ORGS = (
    ("demo-org-a", "Demo Health Network A (synthetic)", (1,)),
    ("demo-org-b", "Demo Health Network B (synthetic)", (2, 3)),
)
DEMO_ROLES = (
    ("admin", Role.SYSTEM_ADMIN),
    ("manager", Role.POPULATION_HEALTH_MANAGER),
    ("coordinator", Role.CARE_COORDINATOR),
    ("clinician", Role.CLINICIAN),
    ("patient", Role.PATIENT),
)
COORDINATOR_ASSIGNMENTS = 20
CLINICIAN_ASSIGNMENTS = 10


@dataclass(frozen=True)
class DemoAccount:
    email: str
    role: str
    organization_slug: str
    password: str | None  # only when generated by this run
    patient_id: str | None = None


def random_password() -> str:
    return secrets.token_urlsafe(18)


@contextmanager
def read_repository() -> Iterator[ReadRepository]:
    if settings.data_source == "memory":
        yield MemoryReadRepository()
        return
    from sqlalchemy.orm import Session

    from app.db.session import get_engine

    with Session(get_engine()) as s:
        yield PostgresReadRepository(s)


def _get_or_create_org(slug: str, name: str, created_by: str | None) -> str:
    with identity_session() as s:
        org = s.scalars(select(Organization).where(Organization.slug == slug)).first()
        if org is None:
            org = directory.create_organization(s, name=name, slug=slug, created_by=created_by)
        return org.organization_id


def _get_or_create_user(email: str, full_name: str, password: str, org_id: str, role: Role,
                        created_by: str | None) -> tuple[str, bool]:
    with identity_session() as s:
        user = auth.get_user_by_email(s, email)
        created = user is None
        if created:
            user = auth.create_user(s, email=email, full_name=full_name, password=password)
        if role != Role.PATIENT:
            directory.add_membership(s, user_id=user.user_id, organization_id=org_id, role=role, created_by=created_by)
        return user.user_id, created


def create_admin(*, email: str, password: str, full_name: str, org_name: str, org_slug: str) -> tuple[str, str]:
    org_id = _get_or_create_org(org_slug, org_name, None)
    user_id, created = _get_or_create_user(email, full_name, password, org_id, Role.SYSTEM_ADMIN, None)
    if not created:
        logger.info("Administrator %s already exists; password unchanged.", user_id)
    return user_id, org_id


def seed_demo(password_for: Callable[[str], str] | None = None) -> list[DemoAccount]:
    accounts: list[DemoAccount] = []
    with read_repository() as repo:
        from app.api.admin import existing_patient_ids

        for slug, name, regions in DEMO_ORGS:
            org_id = _get_or_create_org(slug, name, None)
            patient_ids = sorted({pid for r in regions for pid in existing_patient_ids(repo, region_id=r)})
            with identity_session() as s:
                owned = directory.organization_patient_ids(s, org_id)
                free = [pid for pid in patient_ids if directory.patient_organization_id(s, pid) in (None, org_id)]
                directory.associate_patients(s, organization_id=org_id, patient_ids=free, created_by=None)
            owned = sorted(set(owned) | set(free))
            letter = slug[-1]
            ids: dict[Role, str] = {}
            for prefix, role in DEMO_ROLES:
                email = f"{prefix}.{letter}@{DEMO_DOMAIN}"
                pw = password_for(email) if password_for else random_password()
                user_id, created = _get_or_create_user(
                    email, f"Demo {prefix.title()} {letter.upper()} (synthetic)", pw, org_id, role, None
                )
                ids[role] = user_id
                accounts.append(DemoAccount(email=email, role=role, organization_slug=slug,
                                            password=pw if created and password_for is None else None))
            # Assignments: coordinator and clinician see a small panel each.
            with identity_session() as s:
                for pid in owned[:COORDINATOR_ASSIGNMENTS]:
                    directory.create_assignment(s, organization_id=org_id, staff_user_id=ids[Role.CARE_COORDINATOR],
                                                patient_id=pid, created_by=ids[Role.POPULATION_HEALTH_MANAGER])
                for pid in owned[:CLINICIAN_ASSIGNMENTS]:
                    directory.create_assignment(s, organization_id=org_id, staff_user_id=ids[Role.CLINICIAN],
                                                patient_id=pid, created_by=ids[Role.POPULATION_HEALTH_MANAGER])
            # Patient account: linked through the regular invitation + date-of-birth verification.
            target = next((pid for pid in owned[:COORDINATOR_ASSIGNMENTS]
                           if (rec := repo.get_patient(pid)) is not None and rec.date_of_birth is not None
                           and rec.open_care_gaps_count > 0), None)
            if target is not None:
                with identity_session() as s:
                    linked = auth.active_patient_link(s, ids[Role.PATIENT])
                if linked is None:
                    with identity_session() as s:
                        _, code = directory.create_invitation(s, organization_id=org_id, patient_id=target,
                                                              created_by=ids[Role.CARE_COORDINATOR])
                    dob = repo.get_patient(target).date_of_birth
                    with identity_session() as s:
                        directory.redeem_invitation(s, user_id=ids[Role.PATIENT], code=code, date_of_birth=dob,
                                                    patient_dob_lookup=lambda pid: repo.get_patient(pid).date_of_birth)
                    linked_pid = target
                else:
                    linked_pid = linked.patient_id
                accounts[-1] = DemoAccount(**{**accounts[-1].__dict__, "patient_id": linked_pid})
    return accounts


def seed_demo_identities_at_startup() -> None:
    """Memory mode only, when `DEMO_IDENTITY_SEED=true` and `DEMO_IDENTITY_PASSWORD` is set."""
    if settings.data_source != "memory":
        logger.warning("DEMO_IDENTITY_SEED is ignored in DATA_SOURCE=db; use `python -m app.services.identity seed-demo`.")
        return
    if settings.demo_identity_password is None or not settings.demo_identity_password.get_secret_value():
        logger.error("DEMO_IDENTITY_SEED=true but DEMO_IDENTITY_PASSWORD is not set; demo users were not created.")
        return
    pw = settings.demo_identity_password.get_secret_value()
    accounts = seed_demo(lambda _email: pw)
    logger.info("Demo identities ready: %s", ", ".join(f"{a.role}:{a.organization_slug}" for a in accounts))
