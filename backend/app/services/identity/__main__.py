"""Identity administration CLI (run from `backend/` with `DATABASE_URL` and `DATA_SOURCE=db`).

    python -m app.services.identity create-admin --email admin@example.org \
        --full-name "Platform Admin" --org-name "Example Health" --org-slug example-health
        # password: PULSEREACH_ADMIN_PASSWORD environment variable, or prompted (not echoed)

    python -m app.services.identity seed-demo
        # synthetic demo organizations/users; passwords: DEMO_IDENTITY_PASSWORD, or random and
        # printed once

Exit codes: 0 ok · 2 invalid input or configuration.
"""

from __future__ import annotations

import argparse
import getpass
import os
import sys

from app.core.i18n import AppError, t


def _admin_password() -> str:
    pw = os.environ.get("PULSEREACH_ADMIN_PASSWORD")
    if pw:
        return pw
    first = getpass.getpass("Administrator password: ")
    if first != getpass.getpass("Repeat password: "):
        raise SystemExit("Passwords do not match.")
    return first


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="app.services.identity")
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("create-admin", help="create the first SYSTEM_ADMIN and organization")
    a.add_argument("--email", required=True)
    a.add_argument("--full-name", required=True)
    a.add_argument("--org-name", required=True)
    a.add_argument("--org-slug", required=True)
    sub.add_parser("seed-demo", help="create synthetic demo organizations and users")
    args = ap.parse_args(argv)

    from app.services.identity import demo

    try:
        if args.cmd == "create-admin":
            user_id, org_id = demo.create_admin(email=args.email, password=_admin_password(),
                                                full_name=args.full_name, org_name=args.org_name,
                                                org_slug=args.org_slug)
            print(f"SYSTEM_ADMIN user_id={user_id} organization_id={org_id}")
            return 0
        shared = os.environ.get("DEMO_IDENTITY_PASSWORD") or None
        accounts = demo.seed_demo((lambda _e: shared) if shared else None)
    except AppError as exc:
        print(f"FATAL: {t(exc.message_key, 'en', **exc.params)}", file=sys.stderr)
        return 2
    print("Synthetic demo accounts (passwords are shown only when generated by this run):")
    for acc in accounts:
        pw = acc.password or ("<DEMO_IDENTITY_PASSWORD>" if shared else "<unchanged>")
        extra = f" patient_id={acc.patient_id}" if acc.patient_id else ""
        print(f"  {acc.organization_slug:<11} {acc.role:<26} {acc.email:<40} {pw}{extra}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
